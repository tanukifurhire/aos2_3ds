/* Which SE ids each character can trigger (offline table for the SE preload in
 * src/app/audio.c). Runs every character against every other with CPU AIs at
 * all difficulties, with random inputs and with hyper pinned, and prints a C
 * table of 64-bit id masks per engine character id.
 * Usage: se_usage [frames per run] */
#include "../src/sim/sim.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static aos_world W;
static uint64_t seen[AOS_NUM_CHARS];

static uint32_t lcg(uint32_t *s) { return *s = *s * 1664525u + 1013904223u; }

int main(int argc, char **argv)
{
	aos_register_all();
	int frames = argc > 1 ? atoi(argv[1]) : 4000;
	for (int a = 3; a <= 18; a++)
		for (int b = 3; b <= 18; b++)
			for (int mode = 0; mode < 4; mode++) {
				int32_t ids[2] = {a, b}, sch[2] = {0, 0}, col[2] = {0, 1};
				aos_match_init(&W, ids, sch, col, 180, 2);
				if (mode) {
					W.difficulty = mode - 1;
					W.p[0].inputSrc = W.p[1].inputSrc = 10;
				}
				uint32_t s = (uint32_t)(a * 977 + b * 31 + mode);
				uint16_t m[2] = {0, 0};
				for (int f = 0; f < frames; f++) {
					for (int k = 0; k < 2; k++) {
						uint32_t r = lcg(&s) >> 8;
						if ((r & 7) == 0)
							m[k] ^= (uint16_t)(1u << ((r >> 3) % 10));
					}
					if (mode >= 2 && (f / 600) % 2)
						W.p[0].hyper = W.p[1].hyper = 3.0f;
					aos_tick(&W, m);
					if (W.flow.matchEnd)
						aos_match_restart(&W);
					for (int i = 0; i < W.se_count; i++) {
						/* attribute to both characters of the pairing; the mirror runs
						 * (a == b) separate what is character specific */
						if (a == b)
							seen[a] |= 1ull << W.se[i];
						else
							seen[0] |= 1ull << W.se[i]; /* index 0: seen in some pairing */
					}
				}
			}
	printf("/* generated by tests/se_usage.c */\n");
	for (int c = 3; c <= 18; c++)
		printf("[%d] = 0x%016llxull,\n", c, (unsigned long long)seen[c]);
	printf("/* union over all pairings: 0x%016llxull */\n", (unsigned long long)seen[0]);
	return 0;
}
