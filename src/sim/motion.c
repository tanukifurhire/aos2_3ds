/* {length, loop} per slot (DAT_008855ec / DAT_008855f0, stride 0x14). */
static const struct { int32_t len; uint8_t loop; } slot_info[AOS_MOTION_SLOTS] = {
	[3] = {100, 1}, [4] = {100, 1}, [5] = {160, 1}, [6] = {160, 1}, [7] = {200, 1},
	[8] = {100, 0}, [9] = {100, 1}, [10] = {200, 1}, [11] = {100, 0}, [12] = {100, 1},
	[13] = {200, 1}, [14] = {200, 1}, [15] = {200, 1}, [16] = {200, 1}, [17] = {200, 1},
	[18] = {200, 1}, [19] = {200, 1}, [22] = {20, 0}, [23] = {20, 0}, [24] = {10, 0},
	[25] = {10, 0}, [26] = {200, 1}, [27] = {200, 1}, [28] = {200, 1}, [30] = {100, 0},
	[31] = {100, 0},
};

static float bits(uint32_t u)
{
	float f;
	memcpy(&f, &u, sizeof f);
	return f;
}

/* keyframe k of a slot: {t, angle, x, y} */
static void key(int first, int k, float out[4])
{
	for (int i = 0; i < 4; i++)
		out[i] = bits(kf[first + k].v[i]);
}

static int slot_first(int32_t slot, int *count)
{
	int first = -1, n = 0;
	for (int i = 0; i < NKF; i++)
		if (kf[i].slot == slot) {
			if (first < 0)
				first = i;
			n++;
		}
	*count = n;
	return first;
}

int32_t aos_motion_len(int32_t slot)
{
	return (slot >= 0 && slot < AOS_MOTION_SLOTS) ? slot_info[slot].len : 0;
}

bool aos_motion_loop(int32_t slot)
{
	return slot >= 0 && slot < AOS_MOTION_SLOTS && slot_info[slot].loop != 0;
}

motion_sample aos_motion_get(int32_t slot, int32_t frame) /* FUN_00527ee0 */
{
	motion_sample m = {0, 0, 0};
	int n, first = (slot >= 0 && slot < AOS_MOTION_SLOTS) ? slot_first(slot, &n) : -1;
	if (first < 0)
		return m; /* empty slot: the original would index an empty vector (never used) */
	int32_t len = slot_info[slot].len;
	float a[4], b[4];
	if (frame == 0) {
		key(first, 0, a);
	} else if (frame < len) {
		int k = 0;
		for (;;) {
			if (k >= n)
				break;
			key(first, k, a);
			if (!((int32_t)((float)len * a[0]) < frame))
				break;
			k++;
		}
		if (k >= n)
			k = n - 1; /* unreachable: last t is 1.0 */
		key(first, k, a);
		if (frame == (int32_t)((float)len * a[0])) {
			/* exact keyframe */
		} else {
			key(first, k - 1, b);
			float f = ((float)frame / (float)len - b[0]) / (a[0] - b[0]);
			a[1] = a[1] * f + (1.0f - f) * b[1];
			a[2] = a[2] * f + (1.0f - f) * b[2];
			a[3] = a[3] * f + (1.0f - f) * b[3];
		}
	} else {
		key(first, n - 1, a);
	}
	m.a = a[1];
	m.x = a[2];
	m.y = a[3];
	return m;
}

motion_sample aos_motion_step(int32_t slot, int32_t *frame)
{
	motion_sample m = aos_motion_get(slot, *frame);
	*frame += 1; /* FUN_00528250 tail */
	if (aos_motion_loop(slot) && aos_motion_len(slot) < *frame)
		*frame -= aos_motion_len(slot);
	return m;
}
